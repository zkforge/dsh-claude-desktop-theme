export function astronautAtlas(document: Document): HTMLCanvasElement {
  const atlas = document.createElement('canvas');
  atlas.width = 40 * poses.length;
  atlas.height = 33;
  const ink = atlas.getContext('2d')!;
  poses.forEach((pose, index) => pose.forEach((row, y) => {
    const pixels = rows[row]!;
    for (let x = 0; x < 40; x++) {
      if (pixels[x] === '.') continue;
      ink.fillStyle = palette[Number(pixels[x])]!;
      ink.fillRect(index * 40 + x, y, 1, 1);
    }
  }));
  return atlas;
}

export function astronautFrame(seconds: number): number {
  return track[Math.floor(seconds * 12) % track.length]!;
}
